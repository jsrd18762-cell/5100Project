@torch.no_grad()
def hidden_jacobians(decoder: nn.Sequential, latent: torch.Tensor, units: np.ndarray, batch_size: int) -> torch.Tensor:
    """计算最终 Linear 输入对瓶颈的导数，返回 [样本,候选,2048]。

    eval 模式下 BN 导数为 gamma/sqrt(running_var+eps)，Dropout 为恒等。
    两个 LeakyReLU 的导数由实际前向值决定；值为零时采用 PyTorch 的负侧
    导数 0.2。所有偏置参与前向计算，不能因其直接导数为零就删去偏置。
    """
    require(not decoder.training and latent.dtype == torch.float32, "求导必须使用 eval 和 float32。")
    bn1, bn2 = decoder[1], decoder[5]
    scale1 = bn1.weight / torch.sqrt(bn1.running_var + bn1.eps)
    scale2 = bn2.weight / torch.sqrt(bn2.running_var + bn2.eps)
    # pandas 可返回只读 NumPy 视图；显式复制索引，避免张量引用只读缓冲区。
    selected = torch.tensor(units, dtype=torch.long, device=latent.device)
    first_weight = decoder[0].weight.index_select(1, selected)
    result = torch.empty((len(latent), len(units), decoder[4].out_features), dtype=torch.float32, device=latent.device)
    # 每个样本使用自己的激活分段，绝不在组织中位激活处替代求导。
    with torch.autocast(device_type=latent.device.type, enabled=False):
        for start in range(0, len(latent), batch_size):
            z = latent[start:start + batch_size]
            a1 = bn1(decoder[0](z))
            a2 = bn2(decoder[4](decoder[3](decoder[2](a1))))
            d1 = torch.where(a1 > 0, 1.0, decoder[2].negative_slope) * scale1
            d2 = torch.where(a2 > 0, 1.0, decoder[6].negative_slope) * scale2
            tangent = d1.unsqueeze(-1) * first_weight.unsqueeze(0)
            tangent = torch.matmul(decoder[4].weight, tangent) * d2.unsqueeze(-1)
            result[start:start + len(z)] = tangent.transpose(1, 2)
    require(torch.isfinite(result).all().item(), "隐藏导数含 NaN/Inf。")
    return result


@torch.no_grad()
def project_jacobians(decoder: nn.Sequential, hidden: torch.Tensor, genes: np.ndarray) -> np.ndarray:
    """最终层线性：J[s,j,g] = sum_h dh[s,j,h] * W_final[g,h]。

    基因分块只改变矩阵乘法的计算批量；返回该块的全部样本，供精确中位数
    与双精度统计使用。输出是 CPU float32，不用半精度中间矩阵。
    """
    with torch.autocast(device_type=hidden.device.type, enabled=False):
        weights = decoder[8].weight.index_select(0, torch.tensor(genes, dtype=torch.long, device=hidden.device))
        block = hidden.reshape(-1, hidden.shape[-1]) @ weights.T
    return block.reshape(len(hidden), hidden.shape[1], len(genes)).cpu().numpy()


def summarize_block(values: np.ndarray) -> dict[str, np.ndarray]:
    """一个块必须包含组织内全部样本；不忽略 NaN，不对分批统计再求中位数。"""
    n = len(values)
    require(n >= 2 and values.dtype == np.float32 and np.isfinite(values).all(), "统计输入数量/精度/有限性错误。")
    mean = values.mean(axis=0, dtype=np.float64)
    # np.std 的两遍算法使用 float64 均值和偏差平方，避免 E[x²]-E[x]² 的抵消。
    sd = values.std(axis=0, dtype=np.float64, ddof=1)
    middle = n // 2
    if n % 2:
        median = np.partition(values, middle, axis=0)[middle].astype(np.float64)
    else:
        ordered = np.partition(values, (middle - 1, middle), axis=0)
        median = (ordered[middle - 1].astype(np.float64) + ordered[middle].astype(np.float64)) / 2
    positive = np.count_nonzero(values > 0, axis=0)
    negative = np.count_nonzero(values < 0, axis=0)
    zero = np.count_nonzero(values == 0, axis=0)
    require(np.all(positive + negative + zero == n), "正/负/零值计数未覆盖全部样本。")
    arrays = dict(mean=mean, std=sd, sem=sd / np.sqrt(n), median=median,
                  positive_fraction=positive / n, negative_fraction=negative / n)
    outputs = {name: value.astype(np.float32) for name, value in arrays.items()}
    require(all(np.isfinite(value).all() for value in outputs.values()), "统计结果无法保存为有限 float32。")
    return outputs


def gradient_qc(decoder: nn.Sequential, latent: np.ndarray, rows: np.ndarray, seed: int) -> dict:
    """用反向自动微分独立核对链式导数，并在未跨分段时核对中心有限差分。

    自动微分检查包含全部 64 个输入维度；有限差分检查三个维度。有限差分
    仍使用 float32，容差显式包含输出相减的舍入误差，不能用它替代自动微分。
    """
    device = decoder[0].weight.device
    rng = np.random.default_rng(seed)
    genes = np.sort(rng.choice(decoder[8].out_features, min(8, decoder[8].out_features), replace=False))
    units = np.arange(decoder[0].in_features)
    entries = []

    def selected_forward(z):
        h = decoder[:8](z.unsqueeze(0))
        return F.linear(h, decoder[8].weight[genes], decoder[8].bias[genes])[0]

    def gates(z):
        a1 = decoder[1](decoder[0](z.unsqueeze(0)))
        a2 = decoder[5](decoder[4](decoder[3](decoder[2](a1))))
        return torch.cat(((a1 > 0).flatten(), (a2 > 0).flatten()))

    for row in rows:
        z = torch.tensor(latent[row], dtype=torch.float32, device=device)
        hidden = hidden_jacobians(decoder, z.unsqueeze(0), units, 1)
        chain = project_jacobians(decoder, hidden, genes)[0]
        with torch.enable_grad():
            reference = torch.autograd.functional.jacobian(selected_forward, z).T.detach().cpu().numpy()
        np.testing.assert_allclose(chain, reference, rtol=2e-4, atol=5e-6,
                                   err_msg="链式梯度与反向自动微分不一致。")
        fd_records = []
        with torch.no_grad():
            base_gates = gates(z)
            for unit in sorted(set((0, len(z) // 2, len(z) - 1))):
                step = 0.01 * max(1.0, abs(float(z[unit])))
                stable = False
                for _ in range(12):
                    plus, minus = z.clone(), z.clone()
                    plus[unit] += step
                    minus[unit] -= step
                    delta = float(plus[unit] - minus[unit])
                    if delta == 0:
                        break
                    if torch.equal(gates(plus), base_gates) and torch.equal(gates(minus), base_gates):
                        stable = True
                        break
                    step /= 2
                if not stable:
                    fd_records.append({"neuron_index": unit, "status": "skipped_activation_boundary_or_float32_resolution"})
                    continue
                upper, lower = selected_forward(plus).cpu().numpy(), selected_forward(minus).cpu().numpy()
                estimate = (upper.astype(np.float64) - lower.astype(np.float64)) / delta
                tolerance = (32 * np.finfo(np.float32).eps * (np.abs(upper) + np.abs(lower) + 1) / delta
                             + 0.002 * np.abs(chain[unit]) + 5e-6)
                require(np.all(np.abs(estimate - chain[unit]) <= tolerance), "中心有限差分核对失败。")
                fd_records.append({"neuron_index": unit, "status": "passed", "actual_interval": delta,
                                   "max_abs_error": float(np.max(np.abs(estimate - chain[unit]))),
                                   "max_tolerance": float(tolerance.max())})
        entries.append({"source_row": int(row), "autograd_max_abs_error": float(np.max(np.abs(chain - reference))),
                        "finite_difference": fd_records})
    return {"status": "passed", "genes": genes.tolist(), "autograd_rtol": 2e-4, "autograd_atol": 5e-6,
            "samples": entries, "sign_interpretation": "local model sensitivity; not a causal effect"}


def save_mappings(inputs: Inputs, root: Path, overwrite: bool) -> None:
    """每个矩阵轴都保存显式映射；抽样文件名采用样本行号，不依赖组织排序。"""
    folder = root / "mappings" / inputs.data.tag
    outputs = [folder / f"{name}.csv" for name in ("sample_map", "gene_map", "neuron_map", "tissue_map", "sampled_sample_map")]
    report = root / "quality_control" / inputs.data.tag / "mappings.json"
    if not begin_stage(report, inputs.config, outputs, overwrite):
        return
    source = inputs.data.sample_map.loc[inputs.data.sample_map.tissue_name.isin(inputs.tissues.tissue_name)]
    mapping = source.merge(inputs.tissues[["tissue_name", "tissue_id"]],
                                          on="tissue_name", how="left", sort=False, validate="many_to_one")
    require(mapping.sample_id.tolist() == source.sample_id.tolist(), "映射连接改变了样本顺序。")
    audit = mapping.set_index("row_index", drop=False).loc[inputs.audit_rows].reset_index(drop=True).copy()
    audit["jacobian_file"] = [f"sampled_jacobians/{inputs.data.tag}/sample_{int(row):05d}.npy" for row in inputs.audit_rows]
    for frame, path in zip((mapping, inputs.genes, inputs.candidates, inputs.tissues, audit), outputs):
        frame.to_csv(path, index=False, float_format="%.17g")
    finish_stage(report, inputs.config, outputs, {"n_audit_samples": len(audit)})


def tissue_config(inputs: Inputs, tissue: pd.Series) -> dict:
    return {**inputs.config, "tissue_id": tissue.tissue_id, "tissue_name": tissue.tissue_name,
            "n_tissue_samples": int(tissue.n_samples)}


def tissue_paths(inputs: Inputs, tissue: pd.Series, root: Path) -> tuple[list[Path], np.ndarray]:
    folder = root / "summaries" / inputs.data.tag / tissue.tissue_id
    rows = np.flatnonzero(inputs.data.sample_map.tissue_name.eq(tissue.tissue_name).to_numpy())
    audits = np.intersect1d(rows, inputs.audit_rows)
    paths = [folder / f"{metric}.npy" for metric in METRICS]
    paths += [root / "sampled_jacobians" / inputs.data.tag / f"sample_{row:05d}.npy" for row in audits]
    return paths, rows


def close_maps(arrays: list[np.memmap]) -> None:
    """Windows 上必须关闭映射句柄；异常时也释放，不遗留被占用的半成品。"""
    for array in arrays:
        array.flush()
        array._mmap.close()


def run_tissue(inputs: Inputs, tissue: pd.Series, root: Path, overwrite: bool) -> dict:
    """组织为续跑单位；完成记录只有在全部矩阵、QC 和指纹写完后才生成。"""
    paths, rows = tissue_paths(inputs, tissue, root)
    report = root / "quality_control" / inputs.data.tag / f"{tissue.tissue_id}.json"
    config = tissue_config(inputs, tissue)
    if not begin_stage(report, config, paths, overwrite):
        return json.loads(report.read_text(encoding="utf-8"))
    require(len(rows) == int(tissue.n_samples), "组织样本数与映射不一致。")
    started = time.perf_counter()
    LOGGER.info("Start %s %s %s: n=%d", inputs.data.tag, tissue.tissue_id, tissue.tissue_name, len(rows))
    arrays = []
    try:
        units = inputs.candidates.neuron_index.to_numpy(dtype=np.int64)
        genes = inputs.genes.expression_row_position.to_numpy(dtype=np.int64)
        audits = np.intersect1d(rows, inputs.audit_rows)
        audit_positions = [int(np.flatnonzero(rows == row)[0]) for row in audits]
        shape = (len(units), len(genes))
        for path in paths:
            arrays.append(np.lib.format.open_memmap(path, mode="w+", dtype=np.float32, shape=shape))
        z = torch.tensor(inputs.data.matrix[rows], dtype=torch.float32, device=inputs.decoder[0].weight.device)
        hidden = hidden_jacobians(inputs.decoder, z, units, inputs.config["sample_batch_size"])
        extrema = {metric: [float("inf"), -float("inf")] for metric in METRICS}
        zero_count = 0
        step = inputs.config["gene_block_size"]
        last_progress = started
        for start in range(0, len(genes), step):
            stop = min(start + step, len(genes))
            block = project_jacobians(inputs.decoder, hidden, genes[start:stop])
            summaries = summarize_block(block)
            zero_count += int(np.count_nonzero(block == 0))
            for index, metric in enumerate(METRICS):
                value = summaries[metric]
                arrays[index][:, start:stop] = value
                extrema[metric][0] = min(extrema[metric][0], float(value.min()))
                extrema[metric][1] = max(extrema[metric][1], float(value.max()))
            for index, position in enumerate(audit_positions, len(METRICS)):
                arrays[index][:, start:stop] = block[position]
            if time.perf_counter() - last_progress >= 30:
                LOGGER.info("%s %s: genes %d/%d", inputs.data.tag, tissue.tissue_id, stop, len(genes))
                last_progress = time.perf_counter()
        del hidden, z
        close_maps(arrays)
        arrays = []
        # 逐块核对保存后的有限性与轴长度；无统计项可以静默缺失。
        for path in paths:
            stored = np.load(path, mmap_mode="r", allow_pickle=False)
            try:
                require(stored.shape == shape and stored.dtype == np.float32, f"{path} 结构错误。")
                require(np.isfinite(stored).all(), f"{path} 含非有限值。")
            finally:
                stored._mmap.close()
        finish_stage(report, config, paths, {
            "n_samples": len(rows), "shape": list(shape), "all_finite": True,
            "metric_min_max": extrema, "zero_gradient_count": zero_count,
            "total_gradient_count": len(rows) * len(units) * len(genes),
            "audit_source_rows": audits.tolist(), "elapsed_seconds": time.perf_counter() - started,
            "exact_median": True, "std_ddof": 1, "all_sample_jacobians_saved": False,
        })
    except BaseException as error:
        write_json(report, {"status": "failed", "configuration": config, "error": str(error)})
        raise
    finally:
        close_maps(arrays)
    LOGGER.info("%s %s %s: n=%d, %.1f s", inputs.data.tag, tissue.tissue_id,
                tissue.tissue_name, len(rows), time.perf_counter() - started)
    return json.loads(report.read_text(encoding="utf-8"))


def storage_estimate(inputs: Inputs, tissues: pd.DataFrame) -> dict:
    """只估算请求范围，续跑时已有 NPY 空间可被利用；另留 2 GB 余量。"""
    matrix_bytes = len(inputs.candidates) * len(inputs.genes) * 4
    selected_names = set(tissues.tissue_name)
    n_audit = sum(inputs.data.sample_map.iloc[row].tissue_name in selected_names for row in inputs.audit_rows)
    return {"summary_bytes": len(tissues) * len(METRICS) * matrix_bytes,
            "audit_bytes": n_audit * matrix_bytes,
            "largest_hidden_jacobian_bytes": int(tissues.n_samples.max()) * len(inputs.candidates) * 2048 * 4,
            "largest_sample_gene_block_bytes": int(tissues.n_samples.max()) * len(inputs.candidates)
                * min(inputs.config["gene_block_size"], len(inputs.genes)) * 4}


def model_status(inputs: Inputs, root: Path, processed: dict[str, dict]) -> dict:
    """仅全部组织均完成且匹配当前配置时标记模型 complete。"""
    states = []
    for _, tissue in inputs.tissues.iterrows():
        report = root / "quality_control" / inputs.data.tag / f"{tissue.tissue_id}.json"
        record = processed.get(tissue.tissue_id)
        if record is None:
            record = json.loads(report.read_text(encoding="utf-8")) if report.exists() else {}
            # 本次范围以外的组织也需核对输出，避免只依据旧完成标记下结论。
            if record.get("status") == "complete" and configurations_match(record.get("configuration"), tissue_config(inputs, tissue)):
                if not all(Path(p).is_file() and file_hash(Path(p)) == h for p, h in record["output_sha256"].items()):
                    record = {}
        matched = record.get("status") == "complete" and configurations_match(record.get("configuration"), tissue_config(inputs, tissue))
        states.append({"tissue_id": tissue.tissue_id, "status": "complete" if matched else "not_complete"})
    return {"status": "complete" if all(r["status"] == "complete" for r in states) else "partial",
            "configuration": inputs.config, "tissues": states}


def self_test(inputs: Inputs) -> None:
    """独立统计例子、零点导数、真实模型梯度、分块输出及续跑的集成检查。"""
    from dataclasses import replace

    report = ROOT / "quality_control/self_test.json"
    write_json(report, {"status": "running"})
    # 偶数样本含正/负/零及大偏置小波动；另检验奇数样本中位数。
    values = np.array([[-3, 0, 1e6], [-1, 0, 1e6 + 1], [1, 0, 1e6 + 2], [7, 0, 1e6 + 3]], dtype=np.float32)[:, None, :]
    for count in (3, 4):
        block = values[:count]
        actual = summarize_block(block)
        reference = block.astype(np.float64)
        np.testing.assert_array_equal(actual["mean"], reference.mean(0).astype(np.float32))
        np.testing.assert_array_equal(actual["std"], reference.std(0, ddof=1).astype(np.float32))
        np.testing.assert_array_equal(actual["sem"], (reference.std(0, ddof=1) / np.sqrt(count)).astype(np.float32))
        np.testing.assert_array_equal(actual["median"], np.median(reference, axis=0).astype(np.float32))
        np.testing.assert_array_equal(actual["positive_fraction"], ((reference > 0).sum(0) / count).astype(np.float32))
        np.testing.assert_array_equal(actual["negative_fraction"], ((reference < 0).sum(0) / count).astype(np.float32))
    np.testing.assert_allclose(summarize_block(values)["mean"][0, 0], 1.0)
    np.testing.assert_allclose(summarize_block(values)["std"][0, 0], np.sqrt(56 / 3), rtol=1e-6)
    for invalid in (values[:1], np.full_like(values, np.nan)):
        try:
            summarize_block(invalid)
        except ValueError:
            pass
        else:
            raise AssertionError("无效统计输入未被拒绝。")

    # 小网络可检查完整 Jacobian；负 BN gamma、非零偏置和精确零激活都覆盖。
    with torch.random.fork_rng():
        torch.manual_seed(629)
        toy = nn.Sequential(nn.Linear(4, 5), nn.BatchNorm1d(5), nn.LeakyReLU(.2), nn.Dropout(.3),
                            nn.Linear(5, 6), nn.BatchNorm1d(6), nn.LeakyReLU(.2), nn.Dropout(.3), nn.Linear(6, 7)).eval()
        with torch.no_grad():
            toy[0].bias.zero_()
            toy[1].weight[0] = -1.5
            toy[5].bias.fill_(.7)
        z = torch.tensor([[0., 0., 0., 0.], [1., -2., 3., -4.]], dtype=torch.float32)
        derivative = project_jacobians(toy, hidden_jacobians(toy, z, np.arange(4), 1), np.arange(7))
        for i in range(2):
            expected = torch.autograd.functional.jacobian(lambda x: toy(x.unsqueeze(0))[0], z[i]).T.detach().numpy()
            np.testing.assert_allclose(derivative[i], expected, rtol=2e-5, atol=1e-7)

    root = ROOT / "quality_control/self_test/pipeline"
    # 完整保留两个最小组织的全部样本，包含偶数/奇数 n；仅选 257 个基因用于文件测试。
    selected_tissues = inputs.tissues.nsmallest(2, "n_samples").sort_values("tissue_id")
    genes = inputs.genes.iloc[np.linspace(0, N_GENES - 1, 257, dtype=int)].copy().reset_index(drop=True)
    genes["matrix_column"] = np.arange(len(genes))
    test_rows = np.flatnonzero(inputs.data.sample_map.tissue_name.isin(selected_tissues.tissue_name))
    audits = np.array([test_rows[0], test_rows[-1]], dtype=np.int64)
    config = {**inputs.config, "sample_scope": "validation_tissues_and_gene_subset", "n_samples": len(test_rows), "n_genes": len(genes),
              "gene_block_size": 127, "audit_rows": audits.tolist(), "audit_selection": "first and last row of check tissues",
              "definitions": {**DEFINITIONS, "audit_sampling": "first and last source row in validation tissues"}}
    subset = replace(inputs, genes=genes, tissues=selected_tissues, audit_rows=audits, config=config)
    save_mappings(subset, root, True)
    gradients = gradient_qc(inputs.decoder, inputs.data.matrix, inputs.audit_rows, inputs.config["audit_seed"])
    for _, tissue in selected_tissues.iterrows():
        run_tissue(subset, tissue, root, True)
        paths, rows = tissue_paths(subset, tissue, root)
        latent = torch.tensor(inputs.data.matrix[rows], device=inputs.decoder[0].weight.device)
        units = inputs.candidates.neuron_index.to_numpy(dtype=np.int64)
        hidden = hidden_jacobians(inputs.decoder, latent, units, 1)
        direct = project_jacobians(inputs.decoder, hidden, genes.expression_row_position.to_numpy(dtype=np.int64))
        reference = summarize_block(direct)
        for metric, path in zip(METRICS, paths):
            np.testing.assert_allclose(np.load(path), reference[metric], rtol=2e-4, atol=5e-6)
        for row in np.intersect1d(rows, audits):
            saved = np.load(root / "sampled_jacobians" / inputs.data.tag / f"sample_{row:05d}.npy")
            np.testing.assert_allclose(saved, direct[np.flatnonzero(rows == row)[0]], rtol=2e-4, atol=5e-6)
        run_tissue(subset, tissue, root, False)  # 已完成项只验证，不重新计算。
    # 刻意改变配置必须被拒绝；不写入任何正式结果目录。
    tissue = selected_tissues.iloc[0]
    bad = replace(subset, config={**subset.config, "gene_block_size": 128})
    try:
        run_tissue(bad, tissue, root, False)
    except FileExistsError:
        pass
    else:
        raise AssertionError("配置变化未被拒绝。")
    write_json(report, {"status": "passed", "model_number": inputs.data.number, "gradient_qc": gradients,
                        "odd_even_medians": True, "signed_statistics_and_zeros": True,
                        "invalid_statistics_rejected": True, "all_toy_jacobian_entries": True,
                        "gene_block_tail_and_sample_batch": True, "n_gene_features": len(genes),
                        "tissue_sample_counts": selected_tissues.n_samples.tolist(),
                        "saved_samples_checked": True, "resume_and_mismatch_checked": True,
                        "note": "Small checks only; no full 20-model analysis was started."})


def main() -> None:
    parser = argparse.ArgumentParser(description="Step4 Decoder Jacobian and tissue summaries")
    parser.add_argument("stage", choices=("check", "self-test", "run"))
    parser.add_argument("--model-start", type=int, default=1)
    parser.add_argument("--model-end", type=int, default=20)
    parser.add_argument("--tissue-start", type=int, default=1)
    parser.add_argument("--tissue-end", type=int, default=54)
    parser.add_argument("--gene-block-size", type=int, default=512)
    parser.add_argument("--sample-batch-size", type=int, default=32)
    parser.add_argument("--device", choices=("auto", "cuda", "cpu"), default="auto")
    parser.add_argument("--overwrite", action="store_true", help="重算所选模型和组织，不影响其他步骤")
    args = parser.parse_args()
    require(1 <= args.model_start <= args.model_end <= N_MODELS, "模型范围必须在 1–20。")
    require(1 <= args.tissue_start <= args.tissue_end <= N_TISSUES, "组织范围必须在 1–54。")
    require(1 <= args.gene_block_size <= 2048 and 1 <= args.sample_batch_size <= 64,
            "gene-block-size 必须为 1–2048，sample-batch-size 必须为 1–64。")
    os.chdir(TRIAL_ROOT)
    (ROOT / "logs").mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(levelname)s | %(message)s",
                        handlers=[logging.FileHandler(ROOT / "logs" / f"{args.stage}.log", encoding="utf-8"), logging.StreamHandler()])
    device = configure_device(args.device)
    numbers = [args.model_start] if args.stage == "self-test" else range(args.model_start, args.model_end + 1)
    checks = []
    try:
        for number in numbers:
            inputs = load_inputs(number, device, args.gene_block_size, args.sample_batch_size)
            selected = inputs.tissues.iloc[args.tissue_start - 1:args.tissue_end]
            estimate = storage_estimate(inputs, selected)
            checks.append({"model_number": number, "n_candidates": len(inputs.candidates),
                           "n_samples": len(inputs.data.matrix), "storage": estimate,
                           "configuration": inputs.config})
            if args.stage == "self-test":
                self_test(inputs)
                return
            if args.stage == "run":
                # 单种子精简只改变调度/绘图代码。完整模型先验证全部已存输出，
                # 随后直接跳过，避免重写历史QC而使下游来源指纹发生变化。
                model_record_path = ROOT / "quality_control" / inputs.data.tag / "model.json"
                if model_record_path.is_file() and not args.overwrite:
                    saved_model = json.loads(model_record_path.read_text(encoding="utf-8"))
                    if (saved_model.get("status") == "complete"
                            and configurations_match(saved_model.get("configuration"), inputs.config)):
                        save_mappings(inputs, ROOT, False)
                        if model_status(inputs, ROOT, {})["status"] == "complete":
                            LOGGER.info("Skip verified complete model without rewriting records: %s", inputs.data.tag)
                            del inputs
                            if device.type == "cuda":
                                torch.cuda.empty_cache()
                            continue
                # 防止不完整模型混合两个代码版本的完成记录；完整历史模型已在上方跳过。
                mappings_record = ROOT / "quality_control" / inputs.data.tag / "mappings.json"
                if mappings_record.is_file() and not args.overwrite:
                    saved_config = json.loads(mappings_record.read_text(encoding="utf-8"))["configuration"]
                    require(saved_config == inputs.config,
                            "模型不完整且代码版本变化；请核对后显式重算该模型全部组织，不能混用来源记录。")
                paths = [p for _, t in selected.iterrows() for p in tissue_paths(inputs, t, ROOT)[0]]
                needed = estimate["summary_bytes"] + estimate["audit_bytes"]
                existing = sum(p.stat().st_size for p in paths if p.is_file())
                require(shutil.disk_usage(ROOT).free >= max(0, needed - existing) + 2_000_000_000,
                        "磁盘空间不足；请释放空间或缩小模型/组织运行范围。")
                save_mappings(inputs, ROOT, args.overwrite)
                qc_folder = ROOT / "quality_control" / inputs.data.tag
                # 每次正式运行先检查数值，包括首次运行和中断后恢复。
                write_json(qc_folder / "model.json", {"status": "running", "configuration": inputs.config})
                write_json(qc_folder / "gradient_check.json", {"status": "running", "configuration": inputs.config})
                gradient_record = gradient_qc(inputs.decoder, inputs.data.matrix, inputs.audit_rows, inputs.config["audit_seed"])
                write_json(qc_folder / "gradient_check.json", {**gradient_record, "configuration": inputs.config})
                processed = {}
                for _, tissue in selected.iterrows():
                    processed[tissue.tissue_id] = run_tissue(inputs, tissue, ROOT, args.overwrite)
                status = model_status(inputs, ROOT, processed)
                write_json(qc_folder / "model.json", status)
                LOGGER.info("%s status: %s", inputs.data.tag, status["status"])
            del inputs
            if device.type == "cuda":
                torch.cuda.empty_cache()
        write_json(ROOT / "quality_control/input_check.json", {"status": "passed", "models": checks,
                   "free_disk_bytes": shutil.disk_usage(ROOT).free,
                   "requested_output_bytes": sum(c["storage"]["summary_bytes"] + c["storage"]["audit_bytes"] for c in checks)})
        write_json(ROOT / "metadata/analysis_design.json", {"definitions": DEFINITIONS,
                   "model_numbers": list(range(1, 21)), "std_ddof": 1, "metrics": list(METRICS),
                   "sample_count_location": "mappings/model_XX/tissue_map.csv and per-tissue QC JSON",
                   "main_scope": "all samples; 54 tissues; Step3 candidates in each model separately"})
        LOGGER.info("Step4 %s completed for requested range.", args.stage)
    except BaseException:
        LOGGER.exception("Step4 %s failed.", args.stage)
        raise


if __name__ == "__main__":
    main()

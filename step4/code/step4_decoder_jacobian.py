def configure_device(requested: str) -> torch.device:
    """关闭自动混合精度和 TF32；记录实际设备，设备变化不会静默续用结果。"""
    require(sklearn.__version__ == "1.9.0", "需要 scikit-learn==1.9.0。")
    torch.set_float32_matmul_precision("highest")
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.backends.cudnn.benchmark = False
    torch.use_deterministic_algorithms(True)
    torch.set_num_threads(4)
    if requested == "auto":
        requested = "cuda" if torch.cuda.is_available() else "cpu"
    require(requested != "cuda" or torch.cuda.is_available(), "CUDA 不可用，请检查环境或明确选择 cpu。")
    return torch.device(requested)


def build_decoder(checkpoint: dict, device: torch.device) -> nn.Sequential:
    """只加载 Decoder，保留全部训练参数和 BN 缓冲区，不分配完整 Encoder。"""
    # meta 构造不占用参数存储；assign=True 接收已验证的 checkpoint 张量。
    with torch.device("meta"):
        decoder = nn.Sequential(
            nn.Linear(64, 512), nn.BatchNorm1d(512), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(512, 2048), nn.BatchNorm1d(2048), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(2048, 60498),
        )
    state = {key.removeprefix("decoder."): value for key, value in checkpoint["model_state_dict"].items()
             if key.startswith("decoder.")}
    decoder.load_state_dict(state, strict=True, assign=True)
    decoder.to(device=device).eval().requires_grad_(False)
    require(all(torch.isfinite(value).all().item() for value in decoder.state_dict().values()),
            "Decoder 参数包含非有限值。")
    return decoder


